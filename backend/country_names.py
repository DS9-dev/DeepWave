def _key(s):
    return re.sub(r"[\W_]+", "", (s or "").casefold().replace("ё", "е"))


_LOOKUP = {}
for _code, _names in list(ISO_NAMES.items()) + list(HISTORIC.items()):
    for _n in _names:
        _LOOKUP.setdefault(_key(_n), _code)
for _n, _code in ALIASES.items():
    _LOOKUP[_key(_n)] = _code


def to_iso(value):
    """'США' → 'US', 'RU' → 'RU', 'XW' → None, неизвестное → None."""
    if not value:
        return None
    v = str(value).strip()
    if re.fullmatch(r"[A-Za-z]{2}", v):
        c = MB_CODES.get(v.upper(), v.upper())
        if c in NOT_COUNTRIES:
            return None
        return c if c in ISO_NAMES or c in HISTORIC else None
    return _LOOKUP.get(_key(v))


def ru_name(code):
    if code in HISTORIC:
        return HISTORIC[code][0]
    n = ISO_NAMES.get(code)
    return n[0] if n else code


def all_countries():
    """[(код, русское название)] — нынешние и исторические, по алфавиту."""
    items = [(c, ru_name(c)) for c in list(ISO_NAMES) + list(HISTORIC)]
    return sorted(items, key=lambda x: x[1].casefold().replace("ё", "е"))
